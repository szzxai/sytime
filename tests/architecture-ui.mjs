import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import fixture from './helpers/app-fixture.cjs';

const app = await fixture.startApp('sytime-react-state-');
let browser;
let checks = 0;
function check(value, message) { assert.ok(value, message); checks++; }
try {
  await app.api('/api/register', { method: 'POST', body: { username: 'state_admin', nickname: '状态测试', password: 'test-password' } });
  const login = (await app.api('/api/login', { method: 'POST', body: { username: 'state_admin', password: 'test-password' } })).data;
  for (const title of ['公告甲', '公告乙']) await app.api('/api/admin/announcements', { method: 'POST', token: login.token, body: { title, content: title + '正文' } });
  browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : undefined });
  const context = await browser.newContext({ reducedMotion: 'reduce' });
  await context.addInitScript(login => { localStorage.setItem('token', login.token); localStorage.setItem('user', JSON.stringify(login.user)); }, login);
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(app.base + '/settings.html#tickets');
  await page.locator('#ticketTitle').fill('兼容表单');
  await page.waitForFunction(() => document.querySelector('#ticketTitle').parentElement.textContent.includes('4 / 40'));
  check(true, 'native uncontrolled fields display current character count');
  await page.locator('#ticketContent').fill('迁移后提交内容');
  let prompted = false;
  page.once('dialog', dialog => { prompted = true; return dialog.dismiss(); });
  await page.locator('.site-nav__link[href="/recipe.html"]').click();
  await page.waitForTimeout(100);
  check(prompted && page.url().includes('/settings.html'), 'client navigation preserves unsaved form when cancelled');
  await page.locator('#ticketSubmit').click();
  await page.waitForFunction(() => document.querySelector('#ticketTitle').value === '');
  check(await page.locator('#ticketContent').inputValue() === '', 'successful ticket submission resets both fields');
  await page.waitForFunction(() => document.querySelector('#ticketTitle').parentElement.textContent.includes('0 / 40'));
  check(true, 'native reset updates counter');
  await page.locator('.site-nav__link[href="/recipe.html"]').click();
  await page.waitForURL('**/recipe.html');
  check(true, 'successful submission clears navigation guard');
  await page.getByRole('button',{name:'全部菜品',exact:true}).click();
  await page.locator('#dishSearch').fill('红烧');
  await page.waitForURL(url => url.searchParams.get('q') === '红烧');
  await page.locator('.site-nav__link[href="/announcements.html"]').click();
  await page.waitForURL('**/announcements.html');
  await page.goBack();
  await page.waitForFunction(() => document.querySelector('#dishSearch')?.value === '红烧');
  check(true, 'back restores recipe URL and input');
  await page.goto(app.base + '/shops.html');
  await page.locator('#shopSearch').fill('店铺筛选');
  await page.waitForURL(url => url.searchParams.get('q') === '店铺筛选');
  await page.locator('#sortSelect').selectOption('rating');
  await page.waitForURL(url => url.searchParams.get('sort') === 'rating');
  await page.locator('.site-nav__link[href="/recipe.html"]').click();
  await page.waitForURL('**/recipe.html');
  await page.goBack();
  await page.waitForFunction(() => document.querySelector('#shopSearch')?.value === '店铺筛选');
  check(await page.locator('#sortSelect').inputValue() === 'rating', 'back restores shop filters and sort');
  await page.locator('#clearShopFilters').click();
  await page.waitForFunction(() => !new URLSearchParams(location.search).has('q'));
  check(await page.locator('#shopSearch').inputValue() === '', 'clearing filters updates address and controls');
  await page.goto(app.base + '/inbox.html?type=system&unread=1');
  await page.locator('#unreadOnly').waitFor();
  check(await page.locator('#unreadOnly').isChecked(), 'inbox unread state derives from URL');
  await page.locator('#unreadOnly').uncheck();
  await page.waitForURL(url => !url.searchParams.has('unread'));
  check(true, 'inbox controls update router state');
  await page.goto(app.base + '/announcements.html');
  const announcements = page.locator('#annList button');
  await announcements.first().click();
  const first = new URL(page.url()).hash;
  await announcements.nth(1).click();
  await page.waitForURL(url => url.hash !== first);
  await page.goBack();
  await page.waitForURL(url => url.hash === first);
  check(await page.locator('#annDetail h2').textContent() === await announcements.first().locator('.master-item__title').textContent(), 'hash history restores selected announcement');
  await context.setOffline(true);
  await page.locator('.offline-bar').waitFor();
  check(await page.locator('.offline-bar').textContent() === '网络已断开，部分功能暂不可用', 'offline banner preserves existing copy');
  await context.setOffline(false);
  await page.locator('.offline-bar').waitFor({ state: 'detached' });
  check(true, 'reconnection removes offline banner');
  const expiredContext = await browser.newContext();
  await expiredContext.addInitScript(() => {
    if (sessionStorage.getItem('seeded-invalid-session')) return;
    sessionStorage.setItem('seeded-invalid-session', '1');
    localStorage.setItem('token', 'expired-invalid-token');
    localStorage.setItem('user', JSON.stringify({ id: 1, username: 'stale', role: 'developer' }));
  });
  const expiredPage = await expiredContext.newPage();
  await expiredPage.goto(app.base + '/settings.html');
  await expiredPage.waitForURL(url => url.pathname === '/login.html');
  check(await expiredPage.evaluate(() => !localStorage.getItem('token') && !localStorage.getItem('user')), 'invalid credentials clear stale session and return protected pages to login');
  check(new URL(expiredPage.url()).searchParams.get('next') === '/settings.html', 'expired login preserves destination');
  await expiredContext.close();
  assert.deepEqual(errors, []); checks++;
  console.log(`${checks} React/router compatibility checks passed; isolated database and uploads.`);
} finally { await browser?.close(); await app.stop(); }
