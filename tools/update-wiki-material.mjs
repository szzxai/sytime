/** Rebuild the scoped reading surface from the pinned upstream distribution.
 * No global selectors are emitted: host navigation and footer keep their styles.
 */
import fs from 'node:fs/promises';
import postcss from 'postcss';
import { format, resolveConfig } from 'prettier';
const version = '9.8.1';
const base = `https://raw.githubusercontent.com/squidfunk/mkdocs-material/${version}/material/templates/assets/stylesheets/`;
const component =
  /\.md-(?:typeset|nav|sidebar|icon|content|grid|main|ellipsis|toggle|overlay|clipboard|dialog|tooltip|button|path|annotation|code|top|search-result)/;
const scope = '.wiki-material';
async function convert(file, palette = false) {
  const response = await fetch(base + file);
  if (!response.ok) throw new Error(`Upstream stylesheet: ${response.status}`);
  const root = postcss.parse(await response.text());
  root.walkRules((rule) => {
    if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    const selectors = rule.selectors.filter((s) =>
      palette
        ? s.startsWith('[data-md-color-scheme=slate]')
        : s.includes(':root') || component.test(s) || /\.highlight(?:table)?\b/.test(s),
    );
    if (!selectors.length) {
      rule.remove();
      return;
    }
    // Markdown is also rendered inside editor/review wrappers. Preserve the
    // upstream full-width mobile code blocks across that extra wrapper.
    const readingSelectors = selectors.flatMap((s) =>
      s.includes('.md-content__inner>')
        ? [s, s.replaceAll('.md-content__inner>', '.wiki-markdown>')]
        : [s],
    );
    rule.selector = readingSelectors
      .filter((s) => !s.includes('[dir=rtl]'))
      .map((s) => {
        s = s.replace(/\[dir=ltr\]\s*/g, '').replace(/^html\s+/, '');
        if (s === ':root') return scope;
        if (palette)
          return s.replace('[data-md-color-scheme=slate]', `html[data-theme='dark'] ${scope}`);
        return `${scope} ${s}`;
      })
      .join(',');
    if (!rule.selector) rule.remove();
  });
  root.walkDecls((d) => {
    d.value = d.value.replace(/(-?[\d.]+)rem\b/g, (_, n) => `calc(var(--wiki-unit) * ${n})`);
  });
  root.walkAtRules((at) => {
    if (at.name === 'charset' || at.name === 'page' || (at.nodes && !at.nodes.length)) at.remove();
  });
  root.walkAtRules(/keyframes$/, (at) => {
    const name = at.params;
    let used = false;
    root.walkDecls(/^animation/, (decl) => {
      if (new RegExp(`\\b${name}\\b`).test(decl.value)) {
        decl.value = decl.value.replaceAll(name, `wiki-material-${name}`);
        used = true;
      }
    });
    if (used) at.params = `wiki-material-${name}`;
    else at.remove();
  });
  root.walkRules((rule) => {
    if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    if (rule.selectors.some((selector) => !selector.includes(scope)))
      throw new Error(`Unscoped upstream selector: ${rule.selector}`);
  });
  return root.toString();
}
const main = await convert('main.57a0d79d.min.css');
const palette = await convert('palette.fb2fffe2.min.css', true);
await fs.writeFile(
  'apps/web/src/styles/wiki-material.css',
  await format(
    `/* Generated by tools/update-wiki-material.mjs from Material for MkDocs ${version}.
 * Copyright Martin Donath. MIT license: wiki-material.LICENSE. */\n${main}\n${palette}\n`,
    { ...(await resolveConfig('apps/web/src/styles/wiki-material.css')), parser: 'css' },
  ),
);
